// 같은 종결어미 연속 규칙. 문장 목록을 받아 위반 메시지를 돌려준다. (대구와 '~적 N' 은 style-check 가 문서 단위로 센다)
export function countRules(sentences) {
  const out = []
  let run = 1
  for (let i = 1; i < sentences.length; i++) {
    const e = ending(sentences[i]), p = ending(sentences[i - 1])
    run = e && e === p ? run + 1 : 1
    if (run >= 4) { out.push(`같은 종결어미 '${e}' 가 네 문장 이상 이어진다`); break }
  }
  return out
}

export const ending = s => (/([가-힣]{1,2})[.\s]*(\[\^\d+\])*\s*$/.exec(s.trim().replace(/\.$/, '')) ?? [])[1] ?? ''
